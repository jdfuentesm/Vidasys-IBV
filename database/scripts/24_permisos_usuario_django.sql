BEGIN;
-- Relación entre usuarios personalizados y grupos de Django.
CREATE TABLE IF NOT EXISTS usuario_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    group_id INTEGER NOT NULL,
    CONSTRAINT uq_usuario_groups UNIQUE (usuario_id, group_id),
    CONSTRAINT fk_usuario_groups_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_groups_group FOREIGN KEY (group_id) REFERENCES auth_group(id) ON DELETE CASCADE
);
-- Relación entre usuarios personalizados y permisos individuales.
CREATE TABLE IF NOT EXISTS usuario_user_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    permission_id INTEGER NOT NULL,
    CONSTRAINT uq_usuario_user_permissions UNIQUE (usuario_id, permission_id),
    CONSTRAINT fk_usuario_permissions_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_permissions_permission FOREIGN KEY (permission_id) REFERENCES auth_permission(id) ON DELETE CASCADE
);
-- Índices para acelerar las consultas de permisos.
CREATE INDEX IF NOT EXISTS idx_usuario_groups_usuario ON usuario_groups(usuario_id);
CREATE INDEX IF NOT EXISTS idx_usuario_groups_group ON usuario_groups(group_id);
CREATE INDEX IF NOT EXISTS idx_usuario_permissions_usuario ON usuario_user_permissions(usuario_id);
CREATE INDEX IF NOT EXISTS idx_usuario_permissions_permission ON usuario_user_permissions(permission_id);
COMMIT;
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
    AND table_name IN (
        'usuario_groups',
        'usuario_user_permissions'
    )
ORDER BY table_name;
